isLandType :: Subtype.Subtype -> Bool
isLandType subtype = case subtype of
  Subtype.Cave -> True
  Subtype.Desert -> True
  Subtype.Forest -> True
  Subtype.Gate -> True
  Subtype.Island -> True
  Subtype.Lair -> True

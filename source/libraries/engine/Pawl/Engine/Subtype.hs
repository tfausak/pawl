  Subtype.Planet -> True
  Subtype.PowerPlant -> True
  Subtype.Sphere -> True
  Subtype.Swamp -> True
  Subtype.Tower -> True
  Subtype.Town -> True
  Subtype.Urzas -> True
  _ -> False

